import cv2, numpy as np
im = cv2.imread('ref/gun_pose3.png')
hsv = cv2.cvtColor(im, cv2.COLOR_BGR2HSV).astype(int)
def s(name, x0,x1,y0,y1):
    p = im[y0:y1,x0:x1].reshape(-1,3).astype(float)
    q = hsv[y0:y1,x0:x1].reshape(-1,3).astype(float)
    print('%-22s n=%3d BGR=%s  H=%5.1f S=%5.1f V=%5.1f'%(name,len(p),np.round(p.mean(0),1),q[:,0].mean(),q[:,1].mean(),q[:,2].mean()))
s('bg',              200,230,10,20)
s('rail brass',      120,140,36,39)
s('muzzle collar',   150,158,55,62)
s('midband bright',   89, 92,55,70)
s('copper tube',      60, 80,50,66)
s('steel tube',      110,140,50,58)
s('steel tube low',  110,140,66,74)
s('bore dark',       173,180,58,68)
s('bore liner ring', 168,171,58,68)
s('lattice hole',     33, 41,64,68)
s('lattice web',      29, 33,55,60)
s('red block',        82, 92,32,36)
s('lug',              99,106,78,81)
